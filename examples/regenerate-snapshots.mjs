#!/usr/bin/env node
/**
 * regenerate-snapshots.mjs
 * ---------------------------------------------------------------------------
 * Re-runs the read-only checks and rewrites the `*-output.txt` snapshots next
 * to them, in UTF-8 (no BOM), so the recorded evidence always matches the
 * current code and the current chain.
 *
 * The snapshots are evidence, not fixtures: they show one real run. Anyone can
 * regenerate them at any time and diff the result.
 *
 *   node examples/regenerate-snapshots.mjs
 *
 * Read-only (GET only). Zero dependencies (Node 18+).
 * ---------------------------------------------------------------------------
 */

import { spawnSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const JOBS = [
  ["xdr-header.mjs", [], "xdr-header-output.txt"],
  ["supply-check.mjs", ["--samples", "40"], "supply-check-output.txt"],
  ["op-check.mjs", ["--ledgers", "12", "--per", "20"], "op-check-output.txt"],
  ["self-test.mjs", [], "self-test-output.txt"],
];

const here = fileURLToPath(new URL(".", import.meta.url));

for (const [file, args, out] of JOBS) {
  process.stdout.write(`  regenerating ${out.padEnd(28)}`);
  const r = spawnSync(process.execPath, [fileURLToPath(new URL(file, import.meta.url)), ...args], {
    cwd: here,
    encoding: "utf8",
    maxBuffer: 64 * 1024 * 1024,
  });
  if (r.status !== 0) {
    console.log("FAILED — the check did not pass, snapshot not written");
    process.stdout.write(`${r.stdout ?? ""}${r.stderr ?? ""}`);
    process.exit(1);
  }
  const header = [
    `# generated by: node examples/${file} ${args.join(" ")}`.replace(/\s+$/, ""),
    "# regenerate:  node examples/regenerate-snapshots.mjs",
    "# this file is generated evidence — do not edit by hand",
    "",
  ].join("\n");
  writeFileSync(new URL(out, import.meta.url), header + String(r.stdout).replace(/\r\n/g, "\n"), "utf8");
  console.log("ok");
}

console.log("  done.\n");
